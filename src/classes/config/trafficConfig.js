// ===== 車輛速度配置 =====
/**
 * 🚗 車輛類型速度設定 (公里/小時)
 *
 * 💡 調整建議：
 * - 城市道路：建議 25-60 km/h
 * - 快速道路：建議 40-80 km/h
 * - 擁擠路段：建議降低最高速度 10-15 km/h
 *
 * ⚠️ 注意：min 不可大於 max，avg 會自動計算
 */
export const speedConfig = {
  // 🚛 大型車輛（巴士、卡車、聯結車等）
  large: {
    min: 25, // 最低速度 - 起步較慢，載重影響
    max: 35, // 最高速度 - 考量安全與法規限制
  },

  // 🚗 小型車輛（轎車、休旅車、掀背車等）
  small: {
    min: 30, // 最低速度 - 較靈活的加速性能
    max: 50, // 最高速度 - 較高的速度上限
  },

  // 🏍️ 機車（重機、速克達、輕型機車等）
  motor: {
    min: 30, // 最低速度 - 起步快但市區限速
    max: 60, // 最高速度 - 考量安全因素
  },
}

// 📊 高速設定（測試用 - 取消註解可啟用）
